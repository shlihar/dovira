<h2>1. Занадто загальні формулювання</h2>
<p>Реальний клієнт пише про конкретику: що замовляв, коли, скільки коштувало, що пішло не так. Фейковий відгук — це набір загальних фраз, які підійдуть будь-якій компанії: «чудовий сервіс», «все швидко та якісно», «рекомендую всім».</p>

<h2>2. Сплеск відгуків за короткий період</h2>
<p>Подивіться на дати. Якщо компанія місяцями отримувала 1–2 відгуки на тиждень, а потім за три дні з'явилося двадцять п'ятизіркових — найімовірніше, це закупівля. Природний потік відгуків більш-менш рівномірний.</p>

<h2>3. Лише крайні оцінки</h2>
<p>У реального бізнесу завжди є середні оцінки: комусь сподобалось, але доставка запізнилась; хтось задоволений товаром, але не ціною. Профіль, де лише «5 зірок» і жодного нейтрального відгуку, виглядає підозріло — особливо якщо відгуків багато.</p>

<h2>4. Однотипна мова та структура</h2>
<p>Замовні відгуки часто пише одна людина або генерує один шаблон: однакова довжина, однакові звороти, схожі помилки. Прочитайте поспіль 5–7 відгуків — якщо вони звучать як один голос, це сигнал.</p>

<h2>5. Автори без історії</h2>
<p>Перевірте профілі авторів, якщо платформа це дозволяє. Обліковий запис, створений учора, з єдиним відгуком — слабке джерело довіри. Реальні користувачі зазвичай мають історію: кілька відгуків про різні компанії за тривалий час.</p>

<h2>6. Відгук не відповідає профілю компанії</h2>
<p>Трапляється, що куплені пакети відгуків пишуть люди, які не бачили ні товару, ні сайту. Звідси дивні деталі: хвалять «швидку доставку» у компанії, яка надає лише консультації, або згадують послуги, яких немає в переліку.</p>

<h2>7. Агресивний негатив без фактів</h2>
<p>Фейковими бувають не лише хвалебні відгуки — конкуренти замовляють і «чорнуху». Ознаки ті самі: жодної конкретики, лише емоції та образи, автор не відповідає на уточнювальні питання, схожі тексти з'являються одночасно на кількох майданчиках.</p>

