<h2>Крок 1. Перевірте право займатися адвокатською діяльністю</h2>
<p>Адвокат в Україні — це не будь-який юрист, а особа зі свідоцтвом про право на заняття адвокатською діяльністю. Перевірити його можна безкоштовно:</p>
<ul>
    <li>У <strong>Єдиному реєстрі адвокатів України (ЄРАУ)</strong> на сайті Національної асоціації адвокатів — за прізвищем побачите номер свідоцтва, регіон і чи не зупинена дія свідоцтва.</li>
    <li>Якщо людини немає в реєстрі — вона не адвокат і не зможе захищати вас у кримінальній справі чи користуватися адвокатською таємницею.</li>
</ul>
<p>Для багатьох задач достатньо юриста без свідоцтва (договори, консультації), але для суду та кримінальних справ адвокатський статус критичний.</p>

<h2>Крок 2. Шукайте спеціалізацію, а не «універсала»</h2>
<p>Право занадто велике, щоб один фахівець однаково добре вів кримінальні, сімейні, податкові та земельні справи. Адвокат, який «робить усе», найчастіше не робить нічого глибоко. Формулюйте запит конкретно: не «потрібен адвокат», а «адвокат у справах про розлучення з поділом майна» чи «захист у справі про ДТП».</p>

