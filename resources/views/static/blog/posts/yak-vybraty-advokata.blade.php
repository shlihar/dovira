<h2>Крок 4. Оцініть досвід у схожих справах</h2>
<p>Питайте прямо: «Скільки справ, подібних до моєї, ви вели за останні два роки? Які результати?» Хороший адвокат відповість конкретно, з прикладами (без розголошення імен клієнтів). Ухильна відповідь на кшталт «у мене великий досвід» — привід продовжити пошук.</p>

<h2>Крок 5. Використайте першу консультацію на повну</h2>
<p>Перша зустріч — це співбесіда, де роботодавець ви. Що варто з'ясувати:</p>
<ul>
    <li><strong>Оцінка перспектив.</strong> Чесний адвокат назве і сильні, і слабкі сторони вашої позиції. Гарантія «100% виграємо» — червоний прапорець: результат суду не може гарантувати ніхто.</li>
    <li><strong>Стратегія.</strong> Які варіанти дій існують, скільки часу займе кожен, які ризики.</li>
    <li><strong>Гонорар.</strong> Фіксована сума, погодинна ставка чи відсоток від результату? Що входить, а що оплачується окремо (експертизи, збори, відрядження)?</li>
    <li><strong>Хто саме вестиме справу.</strong> У великих компаніях консультує партнер, а працює помічник. Це нормально, але ви маєте це знати заздалегідь.</li>
</ul>

<h2>Крок 6. Зафіксуйте домовленості письмово</h2>
<p>Договір про надання правової допомоги — обов'язковий. У ньому мають бути: предмет (яка саме справа), розмір і порядок оплати гонорару, обсяг робіт. Адвокат, який пропонує працювати «на довірі» без договору, створює ризики насамперед для вас.</p>

